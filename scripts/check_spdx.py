"""Check first-party identifiers and shadcn provenance."""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "SPDX-License-Identifier: AGPL-3.0-or-later"
SHADCN_HEADER = "SPDX-License-Identifier: MIT"
SOURCE_SUFFIXES = {".py", ".ts", ".tsx", ".js", ".mjs", ".css", ".html", ".svg", ".sh", ".ps1"}
CONFIG_SUFFIXES = {".yml", ".yaml", ".toml", ".ini"}
SPECIAL_FILES = {
    ".dockerignore",
    ".env.example",
    ".gitignore",
    "deploy/linux/Dockerfile.api",
    "deploy/linux/marc-uni-os.service.example",
    "deploy/macos/de.marc.uni-os.plist.example",
    "frontend/.gitignore",
}
EXCLUDED_FILES = {
    "alembic/script.py.mako",  # Alembic's generated template
    "docs/BAUAUFTRAG.md",  # User-provided project specification
}
EXCLUDED_PREFIXES = (
    "desktop/src-tauri/vendor/glib/",  # gtk-rs MIT sources; THIRD_PARTY_NOTICES.md
    "frontend/src/generated/",  # Generated from the OpenAPI schema
    "desktop/src-tauri/permissions/autogenerated/",  # Regenerated by tauri-build
)


def is_first_party_text(path: str) -> bool:
    if path in EXCLUDED_FILES or path.startswith(EXCLUDED_PREFIXES):
        return False
    if path in SPECIAL_FILES:
        return True
    suffix = Path(path).suffix
    return suffix in SOURCE_SUFFIXES or suffix in CONFIG_SUFFIXES or suffix == ".md"


def main() -> int:
    tracked = subprocess.check_output(["git", "-C", str(ROOT), "ls-files", "-z"])
    errors = []
    checked = 0
    for raw in tracked.split(b"\0"):
        if not raw:
            continue
        relative = os.fsdecode(raw)
        path = ROOT / relative
        if (relative.startswith("frontend/src/components/ui/")
                or relative == "frontend/src/vendor/shadcn-tailwind.css"):
            if SHADCN_HEADER not in path.read_text(encoding="utf-8")[:400]:
                errors.append(f"MIT-Kennung fehlt: {relative}")
            continue
        if not is_first_party_text(relative):
            continue
        checked += 1
        if HEADER not in path.read_text(encoding="utf-8")[:400]:
            errors.append(f"AGPL-Kennung fehlt: {relative}")
    if errors:
        for error in errors:
            print(error)
        return 1
    print(f"SPDX-Kennungen geprüft: {checked} eigene Textdateien")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
