async function editor(page: Page) {
  const created = await page.request.post('/api/notes', { data: { course_id: 1, title: 'Werkzeuge · Testnotiz', body: 'Vorlesung' } })
  expect(created.ok()).toBeTruthy()
  const id = (await created.json()).note.id
  await page.goto(`/notes?id=${id}`)
  await page.getByRole('button', { name: 'Bearbeiten', exact: true }).click()
  await expect(page.locator('.studio-document')).toBeVisible()
  await page.getByRole('textbox', { name: 'Notizinhalt', exact: true }).press('ControlOrMeta+End')
  return id
}
async function slash(page: Page, command: string) {
  const body = page.getByRole('textbox', { name: 'Notizinhalt', exact: true })
  await body.press('ControlOrMeta+End'); await body.press('Enter')
  await body.pressSequentially(`/${command}`); await body.press('Tab')
}
async function saved(page: Page, id: number) {
  await expect(page.getByRole('status').filter({ hasText: 'Auf dem Hauptgerät gespeichert' })).toBeVisible()
  return (await (await page.request.get(`/api/notes/${id}`)).json()).body as string
}

test('keyboard-only formula entry restores the caret and variable matrices roundtrip', async ({ page }) => {
  const id = await editor(page)
  const body = page.getByRole('textbox', { name: 'Notizinhalt', exact: true })
  await body.press('ControlOrMeta+Shift+M')
  let dialog = page.getByRole('dialog', { name: 'Formel schreiben', exact: true })
  await expect(dialog.locator('math-field')).toBeFocused()
  await page.keyboard.type('dx+ii+ee')
  await expect(dialog.getByRole('button', { name: 'Formel einfügen', exact: true })).toBeEnabled()
  await page.keyboard.press('ControlOrMeta+Enter')
  await expect(body).toBeFocused()
  await page.keyboard.type(' weiter')
  await expect(body).toContainText('weiter')
  await slash(page, 'matrix')
  dialog = page.getByRole('dialog', { name: 'Formel schreiben', exact: true })
  await dialog.locator('summary').filter({ hasText: 'LaTeX bearbeiten' }).click()
  await dialog.getByRole('textbox', { name: 'LaTeX bearbeiten', exact: true }).fill('')
  await dialog.locator('summary').filter({ hasText: 'Matrixgröße wählen' }).click()
  await dialog.getByRole('spinbutton', { name: 'Zeilen', exact: true }).fill('3')
  await dialog.getByRole('spinbutton', { name: 'Spalten', exact: true }).fill('2')
  await dialog.getByRole('button', { name: 'Matrix einsetzen', exact: true }).press('Enter')
  await expect(dialog.locator('math-field')).toBeFocused()
  await expect(dialog.getByRole('button', { name: 'Formel einfügen', exact: true })).toBeDisabled()
  for (const value of ['1', '2', '3', '4', '5', '6']) {
    await page.keyboard.type(value)
    if (value !== '6') await page.keyboard.press('Tab')
  }
  await expect(dialog.getByRole('button', { name: 'Formel einfügen', exact: true })).toBeEnabled()
  await page.keyboard.press('ControlOrMeta+Enter')
  await expect(dialog).toHaveCount(0)
  await expect(body.locator('.studio-math .katex')).toHaveCount(2)
  const markdown = await saved(page, id)
  expect(markdown).toContain('pmatrix'); expect(markdown).toContain('weiter')
  expect(markdown).not.toContain('placeholder')
  await page.getByRole('button', { name: 'Schließen', exact: true }).click()
  await page.reload()
  await expect(page.locator('.rendered-note .katex')).toHaveCount(2)
})

