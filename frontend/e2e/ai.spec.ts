import { expect, test } from './fixtures'

test('AI package requires a course permission and downloads the selected course', async ({ page }) => {
  await page.addInitScript(() =>
    localStorage.setItem('marc-ui-preferences-v1', JSON.stringify({ modules: { ai: true } })),
  )
  await page.goto('/more')
  await page.locator('.more-tools > summary').click()
  await page.getByRole('link', { name: 'KI-Paket' }).click()
  await expect(page.getByRole('heading', { name: 'KI-Paket' })).toBeVisible()
  const examStatus = page.getByRole('checkbox', {
    name: 'Prüfungsanmeldestatus für die lokale KI-Verbindung freigeben',
  })
  const submissionStatus = page.getByRole('checkbox', {
    name: 'Gespeicherten Abgabestatus für die lokale KI-Verbindung freigeben',
  })
  await expect(examStatus).not.toBeChecked()
  await expect(submissionStatus).not.toBeChecked()
  await examStatus.check()
  await expect(examStatus).toBeChecked()
  await examStatus.uncheck()
  await submissionStatus.check()
  await expect(submissionStatus).toBeChecked()
  await submissionStatus.uncheck()
  await expect(page.getByText('Noch nicht eingerichtet.')).toBeVisible()
  const timetable = page.getByRole('checkbox', { name: 'Stundenplan für die KI-Verbindung freigeben' })
  const mail = page.getByRole('checkbox', { name: 'Mail-Hinweise für die KI-Verbindung freigeben' })
  await expect(timetable).not.toBeChecked()
  await expect(mail).not.toBeChecked()
  await timetable.check()
  await mail.check()
  await page.getByRole('button', { name: 'KI-Verbindung einrichten' }).click()
  await expect(page.getByText('Für lokale KI-Programme freigegeben.')).toBeVisible()
  await page.getByRole('button', { name: 'Verbindung sofort ausschalten' }).click()
  await expect(page.getByText('Zurzeit ausgeschaltet.')).toBeVisible()
  await page.getByRole('button', { name: 'Verbindung einschalten' }).click()
  await expect(page.getByText('Für lokale KI-Programme freigegeben.')).toBeVisible()
  await timetable.uncheck()
  await mail.uncheck()
  await page.getByRole('combobox', { name: 'Kurs' }).selectOption({ label: 'Programmieren 1' })
  const course = page.getByRole('checkbox', { name: 'Programmieren 1', exact: true })
  await expect(course).toBeChecked()
  await course.uncheck()
  await expect(page.getByRole('button', { name: 'Kartenpaket herunterladen' })).toBeDisabled()
  await course.check()
  await page.getByLabel('Download-Datum ab').fill('2999-01-01')
  await page.getByRole('checkbox', { name: 'Nur ausgewähltes Material verwenden' }).check()
  await expect(page.getByText('Kein Material mit Text')).toBeVisible()
  await page.getByLabel('Download-Datum ab').fill('')
  await expect(page.getByRole('button', { name: 'Kartenpaket herunterladen' })).toBeDisabled()
  await page.getByRole('checkbox', { name: /04_Schleifen\.pdf/ }).check()
  await page.getByRole('button', { name: 'Pakettext anzeigen' }).click()
  await expect(page.getByRole('textbox', { name: 'Pakettext' })).toHaveValue(/Schleifen und Python Beispiele/)
  await page.getByRole('button', { name: 'Text kopieren' }).click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Kartenpaket herunterladen' }).click()
  expect((await download).suggestedFilename()).toMatch(/ki-cards-kurs-\d+\.zip/)
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.getByRole('combobox', { name: 'Bereich' }).selectOption('period')
  await page.getByLabel('Download-Datum ab').fill('2000-01-01')
  await expect(page.getByRole('button', { name: 'Kartenpaket herunterladen' })).toBeEnabled()
  const periodDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Kartenpaket herunterladen' }).click()
  expect((await periodDownload).suggestedFilename()).toBe('ki-cards-zeitraum.zip')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
